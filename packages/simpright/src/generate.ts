// --- .github/workflows/squash-gh-pages.yml ---

function squashWorkflow(c: Context): string {
  return lines(
    GENERATED_HEADER,
    'name: Squash GitHub Pages History',
    '',
    "# Replaces the gh-pages branch's history with one commit of the current site (the squash-pages action).",
    '# Each publish adds a full report to the history, so without this the branch grows forever even though',
    '# the site keeps only the latest runs. The site itself doesn\'t change. Monthly, and by hand.',
    '',
    'on:',
    '  workflow_dispatch:',
    '  schedule:',
    `    # ${describeCron(SQUASH_SCHEDULE)}, never on the hour.`,
    `    - cron: ${q(SQUASH_SCHEDULE)}`,
    '',
    'permissions:',
    '  contents: write # force-push gh-pages',
    '',
    'concurrency:',
    '  group: squash-gh-pages',
    '  cancel-in-progress: false',
    '',
    'jobs:',
    '  squash:',
    '    runs-on: ubuntu-latest',
    '    timeout-minutes: 10',
    '',
    '    steps:',
    checkout(c, 'Only the squash step gets a token.'),
    '',
    '      - name: Squash gh-pages',
    `        uses: ${c.kitUses('squash-pages')}`,
    '        with:',
    '          token: ${{ github.token }}',
  );
}

// --- .github/dependabot.yml ---

function dependabot(c: Context): string {
  const target = c.workBranch ? `    target-branch: "${c.workBranch}"` : undefined;
  const schedule = ['    schedule:', '      interval: "weekly"', `      day: "${DEPENDABOT_DAY}"`];
  const registries = c.registry ? ['    registries:', '      - github-packages'] : [];
  const cooldown = ['    cooldown:', `      default-days: ${COOLDOWN_DAYS}`];
  return lines(
    GENERATED_HEADER,
    'version: 2',
    c.workBranch && [
      `# Version updates go to ${c.workBranch} and reach ${c.defaultBranch} through the usual ${c.workBranch} -> ${c.defaultBranch} PR.`,
      `# Security updates ignore target-branch and always open against ${c.defaultBranch} (the default branch).`,
    ],
    c.registry && [
      '',
      'registries:',
      `  # The optional private coverage package (${c.registry.packageName}). ${DEPENDABOT_REGISTRY_SECRET} is a`,
      '  # Dependabot secret: a classic token with read:packages only.',
      '  github-packages:',
      '    type: npm-registry',
      `    url: ${c.registry.url}`,
      `    token: \${{ secrets.${DEPENDABOT_REGISTRY_SECRET} }}`,
    ],
    '',
    'multi-ecosystem-groups:',
    "  # The SimpRight Kit is one release: its npm packages and its actions move in one PR (simpright doctor checks that",
    '  # they agree). The two updates that join this group take only the kit; the others ignore it.',
    '  simpright-kit:',
    c.workBranch && `    target-branch: "${c.workBranch}"`,
    schedule,
    '    commit-message:',
    '      prefix: "deps"',
    '',
    'updates:',
    '  - package-ecosystem: "npm"',
    '    directory: "/"',
    '    multi-ecosystem-group: "simpright-kit"',
    '    patterns:',
    '      - "simpright"',
    '      - "@simpright/*"',
    registries,
    '    # A new version is proposed only after 7 days, so a hijacked release has time to be caught and pulled.',
    cooldown,
    '',
    '  - package-ecosystem: "github-actions"',
    '    directory: "/"',
    '    multi-ecosystem-group: "simpright-kit"',
    '    patterns:',
    `      - "${KIT_REPO}*"`,
    cooldown,
    '',
    '  - package-ecosystem: "npm"',
    '    directory: "/"',
    target,
    registries,
    schedule,
    '    # A new version is proposed only after 7 days, so a hijacked release has time to be caught and pulled.',
    '    # Security updates are not delayed.',
    cooldown,
    '    open-pull-requests-limit: 5',
    '    ignore:',
    '      # The simpright-kit group updates these.',
    '      - dependency-name: "simpright"',
    '      - dependency-name: "@simpright/*"',
    '    groups:',
    '      # One PR for all minor/patch bumps; major versions get their own PR.',
    '      minor-and-patch:',
    '        update-types:',
    '          - "minor"',
    '          - "patch"',
    '    commit-message:',
    '      prefix: "deps"',
    '',
    '  - package-ecosystem: "github-actions"',
    '    directory: "/"',
    target,
    schedule,
    cooldown,
    '    ignore:',
    "      # The simpright-kit group updates the kit's actions.",
    `      - dependency-name: "${KIT_REPO}*"`,
    '    # The actions are pinned to commit SHAs with the version in a comment; Dependabot updates both.',
    '    groups:',
    '      github-actions:',
    '        patterns:',
    '          - "*"',
    '    commit-message:',
    '      prefix: "ci"',
  );
}
